# CLEAN IMAGE GENERATION
def clean_image(intensity, shape=(64, 64), sigma_x=50, sigma_y=10):
    """
    This function generates the elongated Guassian blob detected by a Cherenkov-telescope.

    input:
        intensity: the maximum intensity recorded at the centre of the bulb, in p.e.
        shape: tuple, the shape of the desired array, default =(64,64)
        sigma_x and sigma_y: desired withd and length of the bulb, default = 50, 10

    output:
        image: the clean image generated
    """
    import numpy as np

    # we start by creating an empty image
    clean_image = np.zeros(shape)

    # find the center within image bounds
    x0 = np.random.randint(int(shape[0] * 0.3), int(shape[0] * 0.7))
    y0 = np.random.randint(int(shape[1] * 0.3), int(shape[1] * 0.7))

    # create the meshgrid
    x, y = np.meshgrid(np.arange(shape[0]), np.arange(shape[1]), indexing='ij')

    #find the differences
    dx = x - x0
    dy = y - y0

    # find the random orientation in the sky
    angle = np.random.uniform(0, np.pi)

    dx_rot = dx * np.cos(angle) - dy * np.sin(angle)
    dy_rot = dx * np.sin(angle) + dy * np.cos(angle)

    # ellipse shape (elongated)
    value = np.exp(-(dx_rot**2 / sigma_x + dy_rot**2 / sigma_y))

    #we have to take into account the intensity
    clean_image += intensity * value 

    return clean_image

#NOISE GENERATION
def noise(sigma_noise=1.65, shape=(64,64)):
    """
    This function generates the random noise typical of the NSB (night sky background) recorded at Cherenkov Telescopes.

    input:
        sigma_noise: amplitude of the variations of noise, default=1.65pe
        shape: desired shape, has to be the the same used at clean_image to sum them, default=(64,64)

    output:
        noise
    """
    import numpy as np
    # we create the NSB, this is a random array with our desired size
    #our noise follows a gaussian with average 0 and standard desviation equal to sigma_noise

    noise = np.random.normal(loc=0, scale=sigma_noise, size = shape)

    return noise

#TIME GENERATION
def time(clean_image, time_arrival=15, time_desv=1, time_max=40):
    """
    This function adds the time of arrival of the maximum intensity for a given clean image
    input and the time of arrival of the different noise of the image

    input:
        clean_image: the clean image generated by clean_image()
        time_arrival: time of arrival of the ray, default=15 ns
        time_desv: desviation of time of arrival of theray, default=1 ns
        time_max: the maximum time that the camera of the telescope records, default=40 ns
    output: 
        time_array: array with the times of arrival of each pixel
    """
    import numpy as np

    #ens guardem la shape
    shape = np.shape(clean_image)

    # creem un array de zeros de la mida de la pròpia imatge
    time_array = np.zeros_like(clean_image)

    #separem el bulb del noise
    mask_bulb = clean_image > 0.1
    mask_noise = ~mask_bulb

    # build full time arrays and select by mask to avoid broadcast issues
    bulb_times = np.random.normal(loc=time_arrival, scale=time_desv, size=shape)
    noise_times = np.random.uniform(low=0.0, high=time_max, size=shape)
    time_array = np.where(mask_bulb, bulb_times, noise_times)

    return time_array


